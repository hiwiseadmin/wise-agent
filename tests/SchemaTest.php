    public function testFieldInfoConstruction(): void
    {
        $field = new FieldInfo();
        $field->name    = 'username';
        $field->type    = 'string';
        $field->comment = '用户名';

        $this->assertSame('username', $field->name);
        $this->assertSame('string', $field->type);
        $this->assertSame('用户名', $field->comment);
    }

    public function testFieldInfoFromArray(): void
    {
        $field = FieldInfo::fromArray([
            'name'         => 'id',
            'type'         => 'int',
            'comment'      => '主键ID',
            'is_primary'   => true,
            'is_nullable'  => false,
            'default_value'=> null,
        ]);

        $this->assertSame('id', $field->name);
        $this->assertSame('int', $field->type);
        $this->assertTrue($field->isPrimary);
        $this->assertFalse($field->isNullable);
    }

    public function testFieldInfoToArray(): void
