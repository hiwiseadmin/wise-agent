    public function testAllCapabilityPipelinesCanBeRegistered(): void
    {
        $discovery = $this->getMockDiscovery();
        $schema = $this->createInventorySchema();

        $allCaps = [];
        foreach (['inventory', 'sales', 'crm', 'content'] as $tag) {
            $cap = BusinessCapabilityResolver::get($tag);
            if ($cap !== null) {
                $allCaps[$tag] = $cap->apply($schema);
            }
        }

        $totalPipelines = 0;
        foreach ($allCaps as $capResult) {
            $totalPipelines += count($capResult->pipelines);
        }

        $this->assertGreaterThan(0, $totalPipelines, 'All builtin capabilities combined should have > 0 pipelines');

        $count = $discovery->registerCapabilityPipelines('all_test', $allCaps);
        $this->assertSame($totalPipelines, $count);
    }
