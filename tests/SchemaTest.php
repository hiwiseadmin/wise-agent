    public function testSecurityAndCapabilityIntegration(): void
    {
        $schema = $this->createInventorySchema();

        $guard = SecurityGuard::fromTableWhitelist([
            'test_product', 'test_stock', 'test_stock_in', 'test_stock_out',
        ]);

        $guard->setWritableFields('test_product', ['name', 'price']);
        $guard->setWritableFields('test_stock_in', ['product_id', 'quantity']);
        $guard->setWritableFields('test_stock_out', ['product_id', 'quantity']);

        $generator = new AiToolGenerator($schema, $guard);
        $tools = $generator->generate();

        $this->assertGreaterThan(0, count($tools));

        foreach ($tools as $tool) {
            $this->assertTrue(
                $guard->isTableAllowed($tool->getTableName())
            );
        }

        $inventoryCap = new InventoryCapability();
        $capTools = $inventoryCap->getTools($schema);

        $autoNames = array_map(function ($t) { return $t->getName(); }, $tools);
        $capNames  = array_map(function ($t) { return $t->getName(); }, $capTools);
        $conflicts = array_intersect($autoNames, $capNames);

        $this->assertEmpty($conflicts, 'No name conflicts between auto and capability tools');
    }

