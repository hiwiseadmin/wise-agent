<?php
declare(strict_types=1);

namespace wise\agent\test;

use PHPUnit\Framework\TestCase;
use wise\agent\contract\ToolInterface;
use wise\agent\tool\ToolRegistry;

/**
 * 工具注册表契约测试（B3-2 / B3-5）
 *
 * 覆盖两类真实缺陷：
 *   1. schema 下发的工具名与 execute() 使用的注册键不一致 → LLM 回调必然失败；
 *   2. 同名注册静默覆盖 → 自动生成的工具可能顶掉显式声明的工具。
 */
class ToolRegistryContractTest extends TestCase
{
    public function testSchemaNameMatchesRegistryKeyForNamespacedTool(): void
    {
        $registry = ToolRegistry::newInstance();
        $registry->register($this->tool('list_users'), 'list_users', 'plugin:demo');

        $schemas = $registry->getToolSchemas();

        $this->assertCount(1, $schemas);

        $wireName = $schemas[0]['function']['name'];
        $this->assertSame('plugin_demo_list_users', $wireName);
        $this->assertMatchesRegularExpression('/^[a-zA-Z0-9_-]+$/', $wireName);
        $this->assertSame('plugin:demo.list_users', $registry->resolveName($wireName));
        $this->assertNotNull($registry->get($wireName));
    }

    public function testAutoGeneratedToolDoesNotOverrideExplicitOne(): void
    {
        $registry = ToolRegistry::newInstance();

        $explicit = $this->tool('order_list', '显式声明');
        $auto     = $this->tool('order_list', '自动生成');

        $registry->register($explicit, 'order_list', 'plugin:shop', ToolRegistry::PRIORITY_EXPLICIT);
        $registry->register($auto, 'order_list', 'plugin:shop', ToolRegistry::PRIORITY_AUTO);

        $this->assertSame(
            '显式声明',
            $registry->get('plugin:shop.order_list')->getDescription(),
            '自动生成不得覆盖显式声明'
        );
        $this->assertSame(
            ToolRegistry::PRIORITY_EXPLICIT,
            $registry->getPriority('plugin:shop.order_list')
        );
    }

    public function testExplicitRegistrationOverridesAutoGenerated(): void
    {
        $registry = ToolRegistry::newInstance();
        $key      = 'plugin:shop.order_list';

        $registry->register($this->tool('order_list', '自动生成'), 'order_list', 'plugin:shop', ToolRegistry::PRIORITY_AUTO);
        $registry->register($this->tool('order_list', '显式声明'), 'order_list', 'plugin:shop', ToolRegistry::PRIORITY_EXPLICIT);

        $this->assertSame('显式声明', $registry->get($key)->getDescription());
        $this->assertSame(ToolRegistry::PRIORITY_EXPLICIT, $registry->getPriority($key));
    }

    public function testRemoveNamespaceAlsoClearsPriority(): void
    {
        $registry = ToolRegistry::newInstance();
        $registry->register($this->tool('x'), 'x', 'plugin:tmp', ToolRegistry::PRIORITY_AUTO);

        $registry->removeNamespace('plugin:tmp');

        $this->assertNull($registry->get('plugin:tmp.x'));
        $this->assertSame(ToolRegistry::PRIORITY_EXPLICIT, $registry->getPriority('plugin:tmp.x'));
    }

    public function testDifferentNamespacesCoexist(): void
    {
        $registry = ToolRegistry::newInstance();

        $registry->register($this->tool('list'), 'list', 'plugin:a');
        $registry->register($this->tool('list'), 'list', 'plugin:b');

        $this->assertNotNull($registry->get('plugin:a.list'));
        $this->assertNotNull($registry->get('plugin:b.list'));
        $this->assertCount(1, $registry->getByNamespace('plugin:a'));
        $this->assertCount(1, $registry->getByNamespace('plugin:b'));
    }

    private function tool(string $name, string $description = 'test'): ToolInterface
    {
        return new class($name, $description) implements ToolInterface {
            public function __construct(private string $toolName, private string $toolDescription)
            {
            }

            public function getName(): string
            {
                return $this->toolName;
            }

            public function getDescription(): string
            {
                return $this->toolDescription;
            }

            public function getParameters(): array
            {
                return ['type' => 'object', 'properties' => []];
            }

            public function execute(array $arguments): string
            {
                return 'ok';
            }

            public function getPermission(): string
            {
                return '';
            }

            public function requireConfirmation(): bool
            {
                return false;
            }

            public function getAccess(): string
            {
                return 'read';
            }

            public function getRiskLevel(): string
            {
                return 'low';
            }
        };
    }
}
