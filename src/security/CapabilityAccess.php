<?php
declare(strict_types=1);

namespace wise\agent\security;

/**
 * AI 能力访问类型常量与命名规范
 *
 * 权限模型（分类骨架 + 细粒度下钻 + 审批兜底）中的「分类」定义在此，
 * 是所有包 / 插件共享的公共词汇表。
 *
 * 权限树结构（由 `ToolPermissionRegistrar` 生成）：
 *
 *   AI 能力                         ai.capability            [分组]
 *   ├─ 全部 AI 能力                 ai.capability.*          [通配，一键全开]
 *   ├─ 只读能力                     ai.access.read           [分组]
 *   │   ├─ 全部只读能力             ai.access.read.*         [通配] ← 日常勾选单元
 *   │   ├─ AI 工具：db_query        ai.tool.db_query         [细粒度下钻]
 *   │   ├─ 插件 smartstock · 查询    plugin:smartstock.auto.list.*
 *   │   └─ 技能：xxx.insight         ai.skill.xxx.insight
 *   ├─ 写入能力                     ai.access.write
 *   │   ├─ 全部写入能力             ai.access.write.*        [通配]
 *   │   └─ ...
 *   ├─ 编排执行                     ai.access.execute
 *   │   ├─ 全部执行能力             ai.access.execute.*
 *   │   └─ ...
 *   └─ 管理能力                     ai.access.admin
 *       └─ 全部管理能力             ai.access.admin.*
 *
 * ⚠️ 类别通配（如 `ai.access.read.*`）**不是字符串前缀匹配**，
 *    因为细粒度标识形如 `ai.tool.db_query` / `plugin:x.auto.list.*`，
 *    并不以 `ai.access.read.` 开头。判定由 `CapabilityAuthorizer` 显式比对：
 *       授予了 `ai.access.{access}.*` → 该类别的所有能力放行。
 */
final class CapabilityAccess
{
    /** 只读：查询 / 检索 / 统计，不改变数据 */
    public const READ = 'read';

    /** 写入：新增 / 修改 / 删除 / 导入导出等产生副作用 */
    public const WRITE = 'write';

    /** 编排执行：Skill 编排、工作流等复合能力（本身不一定直接改数据） */
    public const EXECUTE = 'execute';

    /** 管理：系统级 / 高危运维能力 */
    public const ADMIN = 'admin';

    /** 全部访问类型（顺序即权限树中的展示顺序） */
    public const ALL = [self::READ, self::WRITE, self::EXECUTE, self::ADMIN];

    /** 访问类型 → 中文名称 */
    public const LABELS = [
        self::READ    => '只读能力',
        self::WRITE   => '写入能力',
        self::EXECUTE => '编排执行',
        self::ADMIN   => '管理能力',
    ];


    public const RISK_LOW    = 'low';
    public const RISK_MEDIUM = 'medium';
    public const RISK_HIGH   = 'high';


    /** 写操作工具类型（唯一判定源，SecurityGuard / AutoGeneratedTool / BaseAutoTool 共用） */
    public const WRITE_TOOL_TYPES = ['create', 'update', 'delete'];

    /** 只读工具类型 */
    public const READ_TOOL_TYPES = ['list', 'get', 'search', 'stats', 'list_with_relation'];

    /** 工具类型 → 中文标签（用于权限树命名） */
    public const TOOL_TYPE_LABELS = [
        'list'               => '查询列表',
        'get'                => '查询详情',
        'search'             => '关键词搜索',
        'stats'              => '统计聚合',
        'create'             => '新增',
        'update'             => '修改',
        'delete'             => '删除',
        'list_with_relation' => '关联查询',
    ];

    /** Skill 分类 → 访问类型（content/data 只产出文本，code 改写文件，business 可能触发业务动作） */
    public const SKILL_CATEGORY_ACCESS = [
        'content'  => self::READ,
        'data'     => self::READ,
        'code'     => self::WRITE,
        'business' => self::EXECUTE,
    ];

    /**
     * Schema 工具类型 → 访问类型
     */
    public static function forToolType(string $toolType): string
    {
        return in_array($toolType, self::WRITE_TOOL_TYPES, true)
            ? self::WRITE
            : self::READ;
    }

    /**
     * Schema 工具类型 → 风险等级（delete 不可逆为高危）
     */
    public static function riskForToolType(string $toolType): string
    {
        return match ($toolType) {
            'delete'           => self::RISK_HIGH,
            'create', 'update' => self::RISK_MEDIUM,
            default            => self::RISK_LOW,
        };
    }

    /**
     * 工具类型中文标签
     */
    public static function labelOfToolType(string $toolType): string
    {
        return self::TOOL_TYPE_LABELS[$toolType] ?? $toolType;
    }

    /**
     * Skill 分类 → 访问类型（未声明的分类保守归为 execute）
     */
    public static function forSkillCategory(string $category): string
    {
        return self::SKILL_CATEGORY_ACCESS[$category] ?? self::EXECUTE;
    }

    /**
     * Skill 分类 → 风险等级
     *
     * Skill 自身通常只产出文本/结构化结果（真正的写入由 Tool 承担），
     * 因此写类 Skill 取中危，仅管理类取高危。
     */
    public static function riskForSkillCategory(string $category): string
    {
        return match (self::forSkillCategory($category)) {
            self::READ  => self::RISK_LOW,
            self::ADMIN => self::RISK_HIGH,
            default     => self::RISK_MEDIUM,
        };
    }


    /** 能力根节点（分组，本身不参与判定） */
    public const ROOT_IDENT = 'ai.capability';

    /** 全部 AI 能力通配（一键全开） */
    public const ALL_IDENT = 'ai.capability.*';

    /** 类别权限前缀，如 ai.access */
    public const ACCESS_PREFIX = 'ai.access';

    /** Skill 权限前缀，如 ai.skill.{skillName} */
    public const SKILL_PREFIX = 'ai.skill';

    /**
     * 类别分组节点标识（如 ai.access.read）
     */
    public static function groupIdent(string $access): string
    {
        return self::ACCESS_PREFIX . '.' . $access;
    }

    /**
     * 类别通配标识（如 ai.access.read.*）
     */
    public static function wildcardIdent(string $access): string
    {
        return self::ACCESS_PREFIX . '.' . $access . '.*';
    }

    /**
     * 访问类型是否合法
     */
    public static function isValid(string $access): bool
    {
        return in_array($access, self::ALL, true);
    }

    /**
     * 归一化访问类型（非法值回退为 execute —— 保守默认：需要显式授权）
     */
    public static function normalize(string $access): string
    {
        $access = strtolower(trim($access));

        return self::isValid($access) ? $access : self::EXECUTE;
    }

    /**
     * 访问类型中文名称
     */
    public static function label(string $access): string
    {
        return self::LABELS[$access] ?? $access;
    }
}
