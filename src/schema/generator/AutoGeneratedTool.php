<?php
declare(strict_types=1);

namespace wise\agent\schema\generator;

use wise\agent\contract\ToolInterface;
use wise\agent\schema\dto\FieldInfo;
use wise\agent\schema\dto\TableInfo;
use wise\agent\schema\params\ToolParams;
use wise\agent\schema\security\SecurityGuard;
use wise\agent\security\CapabilityAccess;

/**
 * 自动生成的 AI Tool 基类
 *
 * 所有由 AiToolGenerator 生成的工具都继承此类。
 * 通过 TableInfo 元数据 + 工具类型动态构建 SQL 查询，而非硬编码。
 *
 * 支持 8 种标准 Tool 类型：
 *   - list:   列表查询（分页 + 排序 + 条件过滤）
 *   - get:    按主键查询单条
 *   - search: 关键词模糊搜索
 *   - stats:  统计聚合（计数/汇总/分组）
 *   - create: 创建记录
 *   - update: 更新记录
 *   - delete: 删除记录（软删除支持）
 *   - list_with_relation: 带关联模型的列表查询
 *
 * 特性：
 *   - 软删除感知：自动过滤 delete_time IS NULL
 *   - 安全守卫集成：自动排除敏感字段 + 系统字段
 *   - 写操作确认：create/update/delete 默认 requireConfirmation = true
 *   - 动态参数 Schema：从 TableInfo 自动生成 JSON Schema 参数
 *   - 访问分类：只读类型 → read，写类型 → write（供权限按读/写分类授权）
 */
class AutoGeneratedTool implements ToolInterface
{
    /** @var string 工具名称 */
    private $name;

    /** @var string 工具描述 */
    private $description;

    /** @var array JSON Schema 参数定义 */
    private $parameters;

    /** @var TableInfo 目标表 Schema */
    private $tableSchema;

    /** @var string 工具类型 */
    private $toolType;

    /** @var SecurityGuard 安全守卫 */
    private $guard;

    /** @var string 插件标识 */
    private $pluginIdent;

    /** @var string 关联关系名（仅 list_with_relation） */
    private $relationName = '';

    /**
     * @param string $name 工具名称
     * @param string $description 工具描述
     * @param ToolParams $params 参数定义
     * @param TableInfo $tableSchema 表 Schema
     * @param string $toolType 工具类型
     * @param SecurityGuard $guard 安全守卫
     * @param string $pluginIdent 插件标识
     */
    public function __construct(
        string $name,
        string $description,
        ToolParams $params,
        TableInfo $tableSchema,
        string $toolType,
        SecurityGuard $guard,
        string $pluginIdent
    ) {
        $this->name         = $name;
        $this->description  = $description;
        $this->parameters   = $params->toJsonSchema();
        $this->tableSchema  = $tableSchema;
        $this->toolType     = $toolType;
        $this->guard        = $guard;
        $this->pluginIdent  = $pluginIdent;
        $this->relationName = $params->relationName;
    }


    /**
     * @inheritDoc
     */
    public function getName(): string
    {
        return $this->name;
    }

    /**
     * @inheritDoc
     */
    public function getDescription(): string
    {
        return $this->description;
    }

    /**
     * @inheritDoc
     */
    public function getParameters(): array
    {
        return $this->parameters;
    }

    /**
     * @inheritDoc
     */
    public function getPermission(): string
    {
        return 'plugin:' . $this->pluginIdent . '.auto.' . $this->toolType . '.' . $this->tableSchema->name;
    }

    /**
     * @inheritDoc
     *
     * 只读类型（list/get/search/stats/list_with_relation）→ read
     * 写类型（create/update/delete）→ write
     */
    public function getAccess(): string
    {
        return CapabilityAccess::forToolType($this->toolType);
    }

    /**
     * @inheritDoc
     *
     * delete 不可逆 → high；create/update → medium；只读 → low
     */
    public function getRiskLevel(): string
    {
        return CapabilityAccess::riskForToolType($this->toolType);
    }

    /**
     * 聚合权限标识（操作类型级，如 plugin:smartstock.auto.delete.*）
     */
    public function getAggregatePermission(): string
    {
        return 'plugin:' . $this->pluginIdent . '.auto.' . $this->toolType . '.*';
    }

    /**
     * @inheritDoc
     */
    public function requireConfirmation(): bool
    {
        return $this->guard->toolTypeRequiresConfirmation($this->toolType);
    }

    /**
     * @inheritDoc
     */
    public function execute(array $arguments): string
    {
        if (!$this->guard->isToolTypeAllowed($this->toolType, $this->tableSchema->name)) {
            return $this->jsonSafe([
                'error'   => 'Access denied',
                'message' => '当前表不在安全白名单内：' . $this->tableSchema->name,
            ]);
        }

        try {
            switch ($this->toolType) {
                case 'list':
                    return $this->executeList($arguments);
                case 'get':
                    return $this->executeGet($arguments);
                case 'search':
                    return $this->executeSearch($arguments);
                case 'stats':
                    return $this->executeStats($arguments);
                case 'create':
                    return $this->executeCreate($arguments);
                case 'update':
                    return $this->executeUpdate($arguments);
                case 'delete':
                    return $this->executeDelete($arguments);
                case 'list_with_relation':
                    return $this->executeListWithRelation($arguments);
                default:
                    return $this->jsonSafe([
                        'error'   => 'Unknown tool type',
                        'message' => '未知的工具类型：' . $this->toolType,
                    ]);
            }
        } catch (\Throwable $e) {
            return $this->jsonSafe([
                'error'   => 'Execution error',
                'message' => 'An internal error occurred while processing your request.',
            ]);
        }
    }


    /**
     * 列表查询：分页 + 排序 + 条件过滤
     */
    private function executeList(array $args): string
    {
        $page     = max(1, (int) ($args['page'] ?? 1));
        $pageSize = min(100, max(1, (int) ($args['page_size'] ?? 20)));

        $query = \think\facade\Db::name($this->tableSchema->name);

        $this->applyFieldFilters($query, $args);

        $allowedSortFields = array_merge(
            [$this->tableSchema->primaryKey],
            $this->tableSchema->getFieldNames()
        );
        $sortField = $args['sort_field'] ?? $this->tableSchema->primaryKey;
        if (!in_array($sortField, $allowedSortFields, true)) {
            $sortField = $this->tableSchema->primaryKey;
        }
        $sortOrder = ($args['sort_order'] ?? 'desc') === 'asc' ? 'asc' : 'desc';
        $query->order($sortField, $sortOrder);

        $this->applySoftDeleteFilter($query);

        $this->applyOwnerScope($query);

        $this->applyReadableFieldsSelect($query);

        $total = $query->count();
        $list  = $query->page($page, $pageSize)->select();

        return $this->jsonSafe([
            'total'     => $total,
            'page'      => $page,
            'page_size' => $pageSize,
            'list'      => $this->toArraySafe($list),
        ]);
    }


    /**
     * 按主键查询单条记录
     */
    private function executeGet(array $args): string
    {
        $id = $args['id'] ?? $args[$this->tableSchema->primaryKey] ?? null;

        if ($id === null) {
            return $this->jsonSafe([
                'error'   => 'Missing parameter',
                'message' => '缺少主键参数 id',
            ]);
        }

        $query = \think\facade\Db::name($this->tableSchema->name);

        $this->applySoftDeleteFilter($query);
        $this->applyOwnerScope($query);
        $this->applyReadableFieldsSelect($query);

        $record = $query->where($this->tableSchema->primaryKey, $id)->find();

        if ($record === null) {
            return $this->jsonSafe([
                'error'   => 'Not found',
                'message' => '未找到记录：' . $this->tableSchema->name . ' #' . $id,
            ]);
        }

        return $this->jsonSafe($this->toArraySafe($record));
    }


    /**
     * 关键词模糊搜索
     */
    private function executeSearch(array $args): string
    {
        $keyword  = $args['keyword'] ?? '';
        $page     = max(1, (int) ($args['page'] ?? 1));
        $pageSize = min(100, max(1, (int) ($args['page_size'] ?? 20)));

        if ($keyword === '') {
            return $this->jsonSafe([
                'error'   => 'Missing parameter',
                'message' => '缺少搜索关键词 keyword',
            ]);
        }

        $query = \think\facade\Db::name($this->tableSchema->name);

        $searchableFields = $this->getValidSearchableFields();
        $fieldNames = array_keys($searchableFields);

        if (!empty($fieldNames)) {
            $query->where(function ($q) use ($fieldNames, $keyword) {
                foreach ($fieldNames as $field) {
                    $q->whereOr($field, 'like', '%' . $keyword . '%');
                }
            });
        }

        $this->applyFieldFilters($query, $args, ['keyword']);

        $this->applySoftDeleteFilter($query);
        $this->applyOwnerScope($query);
        $this->applyReadableFieldsSelect($query);

        $query->order($this->tableSchema->primaryKey, 'desc');

        $total = $query->count();
        $list  = $query->page($page, $pageSize)->select();

        return $this->jsonSafe([
            'keyword'   => $keyword,
            'total'     => $total,
            'page'      => $page,
            'page_size' => $pageSize,
            'list'      => $this->toArraySafe($list),
        ]);
    }


    /**
     * 统计聚合：计数/汇总/分组
     */
    private function executeStats(array $args): string
    {
        $statType   = $args['stat_type'] ?? 'count';
        $groupField = $args['group_field'] ?? null;

        $query = \think\facade\Db::name($this->tableSchema->name);

        $this->applySoftDeleteFilter($query);
        $this->applyOwnerScope($query);

        $this->applyFieldFilters($query, $args, ['stat_type', 'group_field']);

        switch ($statType) {
            case 'count':
                return $this->statsCount($query, $args);

            case 'summary':
                return $this->statsSummary($query);

            case 'group_by':
                return $this->statsGroupBy($query, $groupField);

            default:
                return $this->jsonSafe([
                    'error'   => 'Unknown stat_type',
                    'message' => '未知的统计类型：' . $statType . '，支持 count/summary/group_by',
                ]);
        }
    }

    /**
     * 计数统计
     */
    private function statsCount($query, array $args): string
    {
        $count = $query->count();
        return $this->jsonSafe(['count' => $count]);
    }

    /**
     * 数值汇总统计（总和/均值/最大/最小）
     */
    private function statsSummary($query): string
    {
        $numericFields = $this->tableSchema->getNumericFields();

        $result = ['count' => $query->count()];
        foreach ($numericFields as $fieldName => $field) {
            if (!($field instanceof FieldInfo)) {
                continue;
            }
            if (preg_match('/_id$/', $fieldName)) {
                continue;
            }

            $fieldExpr = $fieldName;
            $result[$fieldName . '_sum'] = (float) $query->sum($fieldExpr);
            $result[$fieldName . '_avg'] = round((float) $query->avg($fieldExpr), 2);
            $result[$fieldName . '_max'] = (float) $query->max($fieldExpr);
            $result[$fieldName . '_min'] = (float) $query->min($fieldExpr);
        }

        return $this->jsonSafe($result);
    }

    /**
     * 分组统计
     */
    private function statsGroupBy($query, ?string $groupField): string
    {
        if ($groupField === null || $groupField === '') {
            return $this->jsonSafe([
                'error'   => 'Missing parameter',
                'message' => 'group_by 统计需要指定 group_field 参数',
            ]);
        }

        if (!$this->guard->isFieldReadable($this->tableSchema->name, $groupField)) {
            return $this->jsonSafe([
                'error'   => 'Access denied',
                'message' => '字段不可读：' . $groupField,
            ]);
        }

        $rows = $query->group($groupField)
            ->field($groupField . ' as value, COUNT(*) as count')
            ->order('count', 'desc')
            ->select();

        return $this->jsonSafe($this->toArraySafe($rows));
    }


    /**
     * 创建新记录
     */
    private function executeCreate(array $args): string
    {
        $data = [];

        foreach ($args as $key => $value) {
            if ($this->guard->isFieldWritable($this->tableSchema->name, $key)) {
                $data[$key] = $value;
            }
        }

        $ownerId = $this->writeOwnerId();
        if ($ownerId !== null) {
            $data[$this->ownerKey()] = $ownerId;
        }

        if (empty($data)) {
            return $this->jsonSafe([
                'error'   => 'No writable fields',
                'message' => '没有提供可写入的字段，请检查字段权限',
            ]);
        }

        try {
            $id = \think\facade\Db::name($this->tableSchema->name)->insertGetId($data);

            return $this->jsonSafe([
                'success' => true,
                'message' => '创建成功',
                'id'      => $id,
            ]);
        } catch (\Throwable $e) {
            return $this->jsonSafe([
                'error'   => 'Create failed',
                'message' => 'An internal error occurred while creating the record.',
            ]);
        }
    }


    /**
     * 按主键更新记录
     */
    private function executeUpdate(array $args): string
    {
        $id = $args['id'] ?? null;

        if ($id === null) {
            return $this->jsonSafe([
                'error'   => 'Missing parameter',
                'message' => '缺少主键参数 id',
            ]);
        }

        $data = [];

        foreach ($args as $key => $value) {
            if ($key === 'id') {
                continue;
            }
            if ($this->guard->isFieldWritable($this->tableSchema->name, $key)) {
                $data[$key] = $value;
            }
        }

        if (empty($data)) {
            return $this->jsonSafe([
                'error'   => 'No writable fields',
                'message' => '没有提供可更新的字段',
            ]);
        }

        if ($this->tableSchema->hasTimestamps && !isset($data['update_time'])) {
            $data['update_time'] = date('Y-m-d H:i:s');
        }

        try {
            $query = \think\facade\Db::name($this->tableSchema->name);
            $this->applySoftDeleteFilter($query);
            $this->applyOwnerScope($query);

            $affected = $query->where($this->tableSchema->primaryKey, $id)->update($data);

            return $this->jsonSafe([
                'success'  => true,
                'message'  => '更新成功',
                'affected' => $affected,
            ]);
        } catch (\Throwable $e) {
            return $this->jsonSafe([
                'error'   => 'Update failed',
                'message' => 'An internal error occurred while updating the record.',
            ]);
        }
    }


    /**
     * 按主键删除记录（支持软删除）
     */
    private function executeDelete(array $args): string
    {
        $id = $args['id'] ?? null;

        if ($id === null) {
            return $this->jsonSafe([
                'error'   => 'Missing parameter',
                'message' => '缺少主键参数 id',
            ]);
        }

        try {
            $query = \think\facade\Db::name($this->tableSchema->name);
            $this->applyOwnerScope($query);

            if ($this->tableSchema->hasSoftDelete) {
                $deleteTimeField = $this->tableSchema->deleteTimeField ?: 'delete_time';
                $now = date('Y-m-d H:i:s');
                $affected = $query->where($this->tableSchema->primaryKey, $id)
                    ->whereNull($deleteTimeField)
                    ->update([$deleteTimeField => $now]);

                return $this->jsonSafe([
                    'success'  => true,
                    'message'  => '软删除成功',
                    'mode'     => 'soft_delete',
                    'affected' => $affected,
                ]);
            }

            $affected = $query->where($this->tableSchema->primaryKey, $id)->delete();

            return $this->jsonSafe([
                'success'  => true,
                'message'  => '删除成功',
                'mode'     => 'hard_delete',
                'affected' => $affected,
            ]);
        } catch (\Throwable $e) {
            return $this->jsonSafe([
                'error'   => 'Delete failed',
                'message' => 'An internal error occurred while deleting the record.',
            ]);
        }
    }


    /**
     * 带关联模型的列表查询
     */
    private function executeListWithRelation(array $args): string
    {
        $page     = max(1, (int) ($args['page'] ?? 1));
        $pageSize = min(100, max(1, (int) ($args['page_size'] ?? 20)));

        $query = \think\facade\Db::name($this->tableSchema->name);

        $this->applyFieldFilters($query, $args);

        $this->applySoftDeleteFilter($query);
        $this->applyReadableFieldsSelect($query);

        $allowedSortFields = array_merge(
            [$this->tableSchema->primaryKey],
            $this->tableSchema->getFieldNames()
        );
        $sortField = $args['sort_field'] ?? $this->tableSchema->primaryKey;
        if (!in_array($sortField, $allowedSortFields, true)) {
            $sortField = $this->tableSchema->primaryKey;
        }
        $sortOrder = ($args['sort_order'] ?? 'desc') === 'asc' ? 'asc' : 'desc';
        $query->order($sortField, $sortOrder);

        $total = $query->count();
        $list  = $query->page($page, $pageSize)->select();

        $listWithRelation = $this->toArraySafe($list);

        if (!empty($this->tableSchema->modelClass) && class_exists($this->tableSchema->modelClass)) {
            try {
                $modelQuery = new $this->tableSchema->modelClass();
                $this->applySoftDeleteFilter($modelQuery);

                $modelList = $modelQuery->page($page, $pageSize)
                    ->order($sortField, $sortOrder)
                    ->select();

                if (method_exists($modelList, 'toArray')) {
                    $listWithRelation = $modelList->toArray();
                }
            } catch (\Throwable $e) {
            }
        }

        return $this->jsonSafe([
            'total'     => $total,
            'page'      => $page,
            'page_size' => $pageSize,
            'relation'  => $this->relationName,
            'list'      => $listWithRelation,
        ]);
    }


    /**
     * 应用软删除过滤条件
     *
     * @param object $query Db 查询对象
     */
    private function applySoftDeleteFilter($query): void
    {
        if ($this->tableSchema->hasSoftDelete) {
            $deleteTimeField = $this->tableSchema->deleteTimeField ?: 'delete_time';
            if (method_exists($query, 'whereNull')) {
                $query->whereNull($deleteTimeField);
            }
        }
    }

    /**
     * 应用可读字段选择
     *
     * @param object $query Db 查询对象
     */
    private function applyReadableFieldsSelect($query): void
    {
        if (!method_exists($query, 'field')) {
            return;
        }

        $readableNames = $this->guard->getReadableFieldNames($this->tableSchema->name);
        if (empty($readableNames)) {
            return;
        }

        $query->field($readableNames);
    }

    /**
     * 应用字段过滤条件
     *
     * @param object $query
     * @param array $args
     * @param string[] $exclude 排除的参数名
     */
    private function applyFieldFilters($query, array $args, array $exclude = []): void
    {
        $reservedArgs = array_merge(
            ['page', 'page_size', 'sort_field', 'sort_order', 'keyword', 'stat_type', 'group_field', 'id'],
            $exclude
        );

        $validFieldNames = $this->getValidFieldNames();

        foreach ($args as $key => $value) {
            if (in_array($key, $reservedArgs, true) || $value === '' || $value === null) {
                continue;
            }

            if (!in_array($key, $validFieldNames, true)) {
                continue;
            }
            if ($this->guard->isFieldReadable($this->tableSchema->name, $key)) {
                if (method_exists($query, 'where')) {
                    $query->where($key, $value);
                }
            }
        }
    }

    /**
     * 获取有效的可搜索字段（排除敏感字段）
     *
     * @return FieldInfo[]
     */
    private function getValidSearchableFields(): array
    {
        $searchable = $this->tableSchema->getSearchableFields();
        $valid = [];

        foreach ($searchable as $fieldName => $field) {
            if ($this->guard->isFieldReadable($this->tableSchema->name, $fieldName)) {
                $valid[$fieldName] = $field;
            }
        }

        return $valid;
    }

    /**
     * 安全转换为数组（兼容 ThinkPHP Collection 和 stdClass）
     *
     * @param mixed $data
     * @return array
     */
    private function toArraySafe($data): array
    {
        if (is_array($data)) {
            return $data;
        }

        if (is_object($data)) {
            if (method_exists($data, 'toArray')) {
                return $data->toArray();
            }
            if (method_exists($data, 'toarray')) {
                return $data->toarray();
            }
            return json_decode(json_encode($data), true);
        }

        return (array) $data;
    }

    /**
     * 安全的 JSON 编码，失败时返回错误信息而非 false
     *
     * @param mixed $data 待编码的数据
     * @return string JSON 字符串
     */
    private function jsonSafe($data): string
    {
        $json = json_encode($data, JSON_UNESCAPED_UNICODE);
        if ($json === false) {
            return '{"error":"Encoding error","message":"JSON encoding failed"}';
        }
        return $json;
    }

    /**
     * 获取表中实际存在的字段名列表，用于 filter 参数白名单校验
     *
     * @return string[]
     */
    private function getValidFieldNames(): array
    {
        $names = [];
        foreach ($this->tableSchema->fields as $field) {
            if ($field instanceof FieldInfo) {
                $names[] = $field->name;
            }
        }
        return $names;
    }


    /**
     * 获取当前表的 owner_key 字段名
     *
     * @return string|null
     */
    private function ownerKey(): ?string
    {
        $key = $this->guard->getOwnerKey($this->tableSchema->name);
        return is_string($key) && $key !== '' ? $key : null;
    }

    /**
     * 获取当前操作者 ID
     *
     * 优先使用后台 CurrentAdmin，回退 session。
     *
     * @return int
     */
    private function currentOperatorId(): int
    {
        try {
            if (class_exists(\app\admin\facade\CurrentAdmin::class)) {
                $id = (int) \app\admin\facade\CurrentAdmin::getAdminId();
                if ($id > 0) {
                    return $id;
                }
            }
        } catch (\Throwable $e) {
        }

        if (function_exists('session')) {
            return (int) (session('admin_id') ?? session('user_id') ?? 0);
        }

        return 0;
    }

    /**
     * 是否为超级管理员（超管不隔离，可查看全部数据）
     *
     * @return bool
     */
    private function isSuperAdmin(): bool
    {
        try {
            if (class_exists(\app\admin\service\AdminService::class)) {
                return (bool) app(\app\admin\service\AdminService::class)->isSuperAdmin();
            }
        } catch (\Throwable $e) {
        }
        return false;
    }

    /**
     * 读操作行级隔离用的 owner 值
     *
     * 仅当 (1) 启用 owner scope (2) 检测到 owner 字段
     * (3) 有操作者 (4) 非超管 时返回操作者 ID，否则 null（不隔离）。
     *
     * @return int|null
     */
    private function readOwnerId(): ?int
    {
        if (!$this->guard->isAutoOwnerScope()) {
            return null;
        }
        if ($this->ownerKey() === null) {
            return null;
        }
        if ($this->isSuperAdmin()) {
            return null;
        }
        $id = $this->currentOperatorId();
        return $id > 0 ? $id : null;
    }

    /**
     * 写操作（创建）时写入的 owner 值
     *
     * 只要检测到 owner 字段且有操作者即返回，用于自动记录数据归属人。
     *
     * @return int|null
     */
    private function writeOwnerId(): ?int
    {
        if ($this->ownerKey() === null) {
            return null;
        }
        $id = $this->currentOperatorId();
        return $id > 0 ? $id : null;
    }

    /**
     * 对查询对象应用行级 owner 隔离
     *
     * @param object $query
     * @return void
     */
    private function applyOwnerScope($query): void
    {
        $oid = $this->readOwnerId();
        if ($oid !== null && method_exists($query, 'where')) {
            $query->where($this->ownerKey(), $oid);
        }
    }


    /**
     * 获取工具类型
     *
     * @return string
     */
    public function getToolType(): string
    {
        return $this->toolType;
    }

    /**
     * 获取目标表名
     *
     * @return string
     */
    public function getTableName(): string
    {
        return $this->tableSchema->name;
    }

    /**
     * 获取插件标识
     *
     * @return string
     */
    public function getPluginIdent(): string
    {
        return $this->pluginIdent;
    }

    /**
     * 获取表 Schema
     *
     * @return TableInfo
     */
    public function getTableSchema(): TableInfo
    {
        return $this->tableSchema;
    }
